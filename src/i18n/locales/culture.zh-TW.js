/**
 * 递归转换语言包中的字符串、数组和普通对象。
 * 这样繁体版本可以复用完整的简体内容结构，只维护必要的人工校正项。
 */
function toTraditional(value) {
  if (typeof value === 'string') {
    // 按 Unicode 字符展开，逐字查询繁体映射。
    return [...value].map((char) => traditionalCharacters[char] ?? char).join('')
  }
  // 数组中的每一项继续递归转换。
  if (Array.isArray(value)) return value.map(toTraditional)
  if (value && typeof value === 'object') {
    // 保留原键名，仅转换对象中的文案值。
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, toTraditional(item)]))
  }
  // 数字、布尔值和空值无需转换。
  return value
}

